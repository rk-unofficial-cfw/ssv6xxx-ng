/*
 * HW crypto for a single STA interface: the AP is HW WSID 0, its pairwise
 * key and the group keys live in the SRAM table (struct ssv6051_hw_sec)
 * and the chip encrypts/decrypts data frames (M_ENG_ENCRYPT on TX,
 * M_ENG_ENCRYPT_SEC on RX).
 *
 * Based on the ssv6xxx driver:
 *   Copyright (c) 2015 South Silicon Valley Microelectronics Inc.
 *   Copyright (c) 2015 iComm Corporation
 */

#include <linux/unaligned.h>

#include "ssv6051.h"

#define SSV_HW_WSID_AP 0

/* Map a mac80211 cipher suite to the firmware cipher enum. The chip
 * inserts/strips IV, MIC/ICV and keeps the PN itself, so no IV space
 * flags are requested. */
enum ssv6051_cipher ssv6051_prepare_key(struct ieee80211_key_conf *key)
{
	switch (key->cipher) {
	case WLAN_CIPHER_SUITE_WEP40:
		return SSV_CIPHER_WEP40;
	case WLAN_CIPHER_SUITE_WEP104:
		return SSV_CIPHER_WEP104;
	case WLAN_CIPHER_SUITE_TKIP:
		/* TKIP MIC is generated by mac80211; mixing and ICV are
		 * done by the chip. */
		key->flags |= IEEE80211_KEY_FLAG_GENERATE_MMIC;
		return SSV_CIPHER_TKIP;
	case WLAN_CIPHER_SUITE_CCMP:
		/* Management frames are encrypted in software by mac80211
		 * (SW_MGMT_TX | RX_MGMT); data frames use the HW engine. */
		key->flags |= IEEE80211_KEY_FLAG_SW_MGMT_TX |
			      IEEE80211_KEY_FLAG_RX_MGMT;
		return SSV_CIPHER_CCMP;
	default:
		/* GCMP, SMS4 and anything else: mac80211 handles it in
		 * software (WPA3/PMF path). */
		return SSV_CIPHER_INVALID;
	}
}

static int ssv6051_write_sram(struct ssv6051_dev *sdev, u32 addr,
			      const void *data, size_t len)
{
	size_t i;
	int ret;

	for (i = 0; i < len; i += sizeof(u32)) {
		u32 w;

		memcpy(&w, (const u8 *)data + i, sizeof(w));
		ret = ssv6051_sdio_write_reg(sdev, addr + i, w);
		if (ret)
			return ret;
	}
	return 0;
}

static u32 ssv6051_group_key_addr(struct ssv6051_dev *sdev, int idx)
{
	return sdev->hw_sec_key + (idx - 1) * sizeof(struct ssv6051_hw_key);
}

static u32 ssv6051_sta_key_addr(struct ssv6051_dev *sdev, int wsid)
{
	return sdev->hw_sec_key + 3 * sizeof(struct ssv6051_hw_key) +
	       wsid * sizeof(struct ssv6051_hw_sta_key);
}

static int ssv6051_write_group_key(struct ssv6051_dev *sdev, int idx)
{
	return ssv6051_write_sram(sdev, ssv6051_group_key_addr(sdev, idx),
				  &sdev->sec_shadow.group_key[idx - 1],
				  sizeof(struct ssv6051_hw_key));
}

static int ssv6051_write_sta_key(struct ssv6051_dev *sdev)
{
	return ssv6051_write_sram(sdev, ssv6051_sta_key_addr(sdev, 0),
				  &sdev->sec_shadow.sta_key[0],
				  sizeof(struct ssv6051_hw_sta_key));
}

/* Only the key index word of the STA entry (pair/group key idx). */
static int ssv6051_write_sta_key_idx(struct ssv6051_dev *sdev)
{
	return ssv6051_write_sram(sdev, ssv6051_sta_key_addr(sdev, 0),
				  &sdev->sec_shadow.sta_key[0], sizeof(u32));
}

static int ssv6051_set_cipher_type(struct ssv6051_dev *sdev, bool group,
				   u8 type)
{
	u32 val;
	int ret;

	ret = ssv6051_sdio_read_reg(sdev, ADR_SCRT_SET, &val);
	if (ret)
		return ret;
	if (group) {
		val &= GRP_SCRT_I_MSK;
		val |= (u32)type << GRP_SCRT_SFT;
	} else {
		val &= PAIR_SCRT_I_MSK;
		val |= (u32)type << PAIR_SCRT_SFT;
	}
	return ssv6051_sdio_write_reg(sdev, ADR_SCRT_SET, val);
}

/* Tell the firmware whether RX of this WSID is HW or SW decrypted
 * (SET_TYPE commands for HW WSIDs). */
static int ssv6051_wsid_cmd(struct ssv6051_dev *sdev, u8 ops, const u8 *addr,
			    u8 sec)
{
	struct ssv6051_host_cmd *host_cmd;
	struct ssv6051_wsid_params *params;
	struct sk_buff *skb;
	size_t len = SSV6051_HOST_CMD_HDR_LEN + sizeof(*params);
	int ret = -EIO, retry;

	skb = dev_alloc_skb(len);
	if (!skb)
		return -ENOMEM;
	skb_put_zero(skb, len);
	host_cmd = (struct ssv6051_host_cmd *)skb->data;
	host_cmd->len = len;
	host_cmd->c_type = HOST_CMD;
	host_cmd->h_cmd = SSV6XXX_HOST_CMD_WSID_OP;
	params = (struct ssv6051_wsid_params *)host_cmd->dat8;
	params->cmd = ops;
	params->wsid_idx = SSV_HW_WSID_AP;
	params->hw_security = sec;
	memcpy(params->target_wsid, addr, ETH_ALEN);

	for (retry = 0; retry < 3 && ret; retry++)
		ret = ssv6051_hci_send_cmd_skb(sdev, skb);
	dev_kfree_skb(skb);
	return ret;
}

/* Flush the WEP default keys to a freshly programmed WSID (key 0 is the pairwise-style key, a non-zero default
 * key index also needs its group slot). */
static int ssv6051_wep_flush(struct ssv6051_dev *sdev)
{
	struct ssv6051_hw_sec *sec = &sdev->sec_shadow;
	u8 def_idx = sec->sta_key[0].pair_key_idx;
	int ret, i;

	sec->sta_key[0].pair_key_idx = 0;
	sec->sta_key[0].group_key_idx = 0;
	ret = ssv6051_write_sta_key(sdev);
	sec->sta_key[0].pair_key_idx = def_idx;
	sec->sta_key[0].group_key_idx = def_idx;
	if (ret)
		return ret;
	for (i = 1; i <= 3; i++) {
		ret = ssv6051_write_group_key(sdev, i);
		if (ret)
			return ret;
	}
	if (def_idx)
		ret = ssv6051_write_sta_key_idx(sdev);
	return ret;
}

int ssv6051_sta_add(struct ieee80211_hw *hw, struct ieee80211_vif *vif,
		    struct ieee80211_sta *sta)
{
	struct ssv6051_dev *sdev = hw->priv;
	struct ssv6051_sta_priv *priv = (void *)sta->drv_priv;
	u32 reg;
	int ret;

	priv->sta = sta;
	priv->hw_wsid = -1;

	/* Only the AP of the STA interface gets the HW WSID. */
	if (vif->type != NL80211_IFTYPE_STATION || sdev->hw_wsid >= 0)
		return 0;

	ret = ssv6051_sdio_write_reg(sdev, ADR_WSID0 + 4,
				     get_unaligned_le32(&sta->addr[0]));
	if (ret)
		return ret;
	ret = ssv6051_sdio_write_reg(sdev, ADR_WSID0 + 8,
				     get_unaligned_le16(&sta->addr[4]));
	if (ret)
		return ret;
	ret = ssv6051_sdio_write_reg(sdev, ADR_WSID0, 1);
	if (ret)
		return ret;
	for (reg = ADR_WSID0_TID0_RX_SEQ; reg <= ADR_WSID0_TID7_RX_SEQ; reg += 4)
		ssv6051_sdio_write_reg(sdev, reg, 0);

	priv->hw_wsid = SSV_HW_WSID_AP;
	sdev->hw_wsid = SSV_HW_WSID_AP;

	ssv6051_wsid_cmd(sdev, SSV6XXX_WSID_OPS_HWWSID_PAIRWISE_SET_TYPE,
			 sta->addr, SSV6XXX_WSID_SEC_SW);
	ssv6051_wsid_cmd(sdev, SSV6XXX_WSID_OPS_HWWSID_GROUP_SET_TYPE,
			 sta->addr, SSV6XXX_WSID_SEC_SW);

	if (sdev->hw_wep)
		ssv6051_wep_flush(sdev);

	ssv_dbg(DBG_KEY, sdev->dev, "STA %pM -> HW WSID %d\n", sta->addr,
		priv->hw_wsid);
	return 0;
}

int ssv6051_sta_remove(struct ieee80211_hw *hw, struct ieee80211_vif *vif,
		       struct ieee80211_sta *sta)
{
	struct ssv6051_dev *sdev = hw->priv;
	struct ssv6051_sta_priv *priv = (void *)sta->drv_priv;

	if (priv->hw_wsid != SSV_HW_WSID_AP)
		return 0;

	sdev->hw_pair_crypt = false;
	ssv6051_sdio_write_reg(sdev, ADR_WSID0, 0);
	sdev->hw_wsid = -1;
	priv->hw_wsid = -1;
	return 0;
}

static int ssv6051_set_key_wep(struct ssv6051_dev *sdev,
			       enum ssv6051_cipher cipher,
			       struct ieee80211_key_conf *key)
{
	struct ssv6051_hw_sec *sec = &sdev->sec_shadow;
	struct ssv6051_hw_sta_key *sk = &sec->sta_key[0];
	int idx = key->keyidx;
	int ret;

	if (idx > 3 || key->keylen > SSV_SECURITY_KEY_LEN)
		return -EOPNOTSUPP;

	sk->pair_key_idx = idx;
	sk->group_key_idx = idx;
	put_unaligned_le16(key->keylen, &sk->reserve[0]);
	if (idx == 0) {
		memset(sk->pair.key, 0, sizeof(sk->pair.key));
		memcpy(sk->pair.key, key->key, key->keylen);
	} else {
		memset(sec->group_key[idx - 1].key, 0,
		       sizeof(sec->group_key[idx - 1].key));
		memcpy(sec->group_key[idx - 1].key, key->key, key->keylen);
	}

	ret = ssv6051_set_cipher_type(sdev, false, cipher);
	if (ret)
		return ret;
	ret = ssv6051_set_cipher_type(sdev, true, cipher);
	if (ret)
		return ret;

	/* Without a WSID yet the keys are flushed by sta_add. */
	if (sdev->hw_wsid >= 0) {
		if (idx == 0) {
			sk->pair_key_idx = 0;
			sk->group_key_idx = 0;
			ret = ssv6051_write_sta_key(sdev);
		} else {
			ret = ssv6051_write_group_key(sdev, idx);
			if (!ret)
				ret = ssv6051_write_sta_key_idx(sdev);
		}
		if (ret)
			return ret;
	}

	sdev->hw_wep = true;
	sdev->hw_pair_crypt = true;
	sdev->hw_group_crypt = true;
	key->hw_key_idx = idx;
	return 0;
}

static int ssv6051_set_key_pairwise(struct ssv6051_dev *sdev,
				    struct ieee80211_sta *sta,
				    enum ssv6051_cipher cipher,
				    struct ieee80211_key_conf *key)
{
	struct ssv6051_hw_sta_key *sk = &sdev->sec_shadow.sta_key[0];
	struct ssv6051_sta_priv *priv;
	int ret;

	if (!sta || key->keylen > SSV_SECURITY_KEY_LEN)
		return -EOPNOTSUPP;
	priv = (void *)sta->drv_priv;
	if (priv->hw_wsid != SSV_HW_WSID_AP)
		return -EOPNOTSUPP;

	memset(&sk->pair, 0, sizeof(sk->pair));
	memcpy(sk->pair.key, key->key, key->keylen);
	sk->pair_key_idx = 0;
	/* group_key_idx keeps the already installed group key, if any */

	ret = ssv6051_write_sta_key(sdev);
	if (ret)
		return ret;
	ret = ssv6051_set_cipher_type(sdev, false, cipher);
	if (ret)
		return ret;

	sdev->hw_pair_crypt = true;
	key->hw_key_idx = 0;
	ssv6051_wsid_cmd(sdev, SSV6XXX_WSID_OPS_HWWSID_PAIRWISE_SET_TYPE,
			 sta->addr, SSV6XXX_WSID_SEC_HW);
	return 0;
}

static int ssv6051_set_key_group(struct ssv6051_dev *sdev,
				 struct ieee80211_vif *vif,
				 enum ssv6051_cipher cipher,
				 struct ieee80211_key_conf *key)
{
	struct ssv6051_hw_sec *sec = &sdev->sec_shadow;
	int idx = key->keyidx;
	int ret;

	if (idx < 1 || idx > 3 || key->keylen > SSV_SECURITY_KEY_LEN ||
	    sdev->hw_wsid < 0)
		return -EOPNOTSUPP;

	memset(&sec->group_key[idx - 1], 0, sizeof(sec->group_key[idx - 1]));
	memcpy(sec->group_key[idx - 1].key, key->key, key->keylen);
	sec->sta_key[0].group_key_idx = idx;

	ret = ssv6051_write_group_key(sdev, idx);
	if (ret)
		return ret;
	ret = ssv6051_write_sta_key_idx(sdev);
	if (ret)
		return ret;
	ret = ssv6051_set_cipher_type(sdev, true, cipher);
	if (ret)
		return ret;

	sdev->hw_group_crypt = true;
	key->hw_key_idx = idx;
	ssv6051_wsid_cmd(sdev, SSV6XXX_WSID_OPS_HWWSID_GROUP_SET_TYPE,
			 vif->bss_conf.bssid, SSV6XXX_WSID_SEC_HW);
	return 0;
}

static void ssv6051_clear_key(struct ssv6051_dev *sdev,
			      enum ssv6051_cipher cipher,
			      struct ieee80211_key_conf *key, bool pairwise)
{
	struct ssv6051_hw_sec *sec = &sdev->sec_shadow;

	if (cipher == SSV_CIPHER_WEP40 || cipher == SSV_CIPHER_WEP104) {
		ssv6051_set_cipher_type(sdev, false, SSV_CIPHER_NONE);
		ssv6051_set_cipher_type(sdev, true, SSV_CIPHER_NONE);
		memset(sec, 0, sizeof(*sec));
		sdev->hw_wep = false;
		sdev->hw_pair_crypt = false;
		sdev->hw_group_crypt = false;
	} else if (pairwise) {
		ssv6051_set_cipher_type(sdev, false, SSV_CIPHER_NONE);
		memset(&sec->sta_key[0].pair, 0, sizeof(sec->sta_key[0].pair));
		sdev->hw_pair_crypt = false;
	} else {
		ssv6051_set_cipher_type(sdev, true, SSV_CIPHER_NONE);
		if (key->keyidx >= 1 && key->keyidx <= 3)
			memset(&sec->group_key[key->keyidx - 1], 0,
			       sizeof(sec->group_key[0]));
		sec->sta_key[0].group_key_idx = 0;
		sdev->hw_group_crypt = false;
	}
}

int ssv6051_set_key(struct ieee80211_hw *hw, enum set_key_cmd cmd,
		    struct ieee80211_vif *vif, struct ieee80211_sta *sta,
		    struct ieee80211_key_conf *key)
{
	struct ssv6051_dev *sdev = hw->priv;
	enum ssv6051_cipher cipher;
	bool pairwise = key->flags & IEEE80211_KEY_FLAG_PAIRWISE;
	int ret;

	cipher = ssv6051_prepare_key(key);
	if (cipher == SSV_CIPHER_INVALID) {
		/* Software cipher (GCMP, SMS4, ...): refuse the HW key so
		 * mac80211 falls back to software crypto. */
		ssv_dbg(DBG_KEY, sdev->dev,
			"cipher 0x%08x handled in software\n", key->cipher);
		return -EOPNOTSUPP;
	}
	if (vif->type != NL80211_IFTYPE_STATION)
		return -EOPNOTSUPP;

	if (cmd == DISABLE_KEY) {
		ssv6051_clear_key(sdev, cipher, key, pairwise);
		return 0;
	}

	if (cipher == SSV_CIPHER_WEP40 || cipher == SSV_CIPHER_WEP104)
		ret = ssv6051_set_key_wep(sdev, cipher, key);
	else if (pairwise)
		ret = ssv6051_set_key_pairwise(sdev, sta, cipher, key);
	else
		ret = ssv6051_set_key_group(sdev, vif, cipher, key);

	ssv_dbg(DBG_KEY, sdev->dev,
		"set key cipher %d idx %d %s wsid %d -> %d\n", cipher,
		key->keyidx, pairwise ? "pairwise" : "group", sdev->hw_wsid,
		ret);
	return ret;
}
